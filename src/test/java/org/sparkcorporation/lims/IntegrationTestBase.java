package org.sparkcorporation.lims;

import java.util.Locale;
import java.util.Map;
import java.util.concurrent.atomic.AtomicInteger;

import org.junit.jupiter.api.Tag;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.http.MediaType;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.web.client.RestClient;
import org.testcontainers.containers.PostgreSQLContainer;

/**
 * Base for integration tests. Uses the Testcontainers <b>singleton pattern</b>: the postgres
 * container is started once in a static initializer and lives for the entire JVM run, then is
 * reaped by the Testcontainers Ryuk sidecar at JVM exit.
 *
 * <p>We deliberately do <em>not</em> use {@code @Testcontainers} + {@code @Container} together with
 * a {@code static} field. Although that pattern looks JVM-scoped, JUnit Jupiter's
 * TestcontainersExtension treats it as per-class: each subclass triggers a fresh {@code start()} /
 * {@code stop()} cycle, the container is recreated on a new port between IT classes, and any cached
 * Spring context from an earlier IT class points at a stale port — manifesting as {@code
 * HikariPool-N — Connection refused} for half the suite.
 *
 * <p>Spring Boot's {@code @ServiceConnection} on the static field still wires JDBC URL / user /
 * password into every {@code @SpringBootTest} context.
 */
@Tag("integration")
@ActiveProfiles("test")
public abstract class IntegrationTestBase {

    /**
     * Global registration-number sequence shared across all IT subclasses. All ITs run against the
     * same singleton Testcontainers PostgreSQL container, so lab-file registration numbers must be
     * globally unique. Each {@code seedLabFile} implementation calls {@code
     * REG_SEQ.getAndIncrement()} for its 4-digit suffix.
     *
     * <p>Starts at 9000 to avoid collisions with registration numbers generated by the
     * application's DB counter (used by order-module ITs that create lab files via {@code POST
     * /api/v1/lab-files}). Those API-created files start at 0001 and will never exceed a few
     * hundred in a single test run, so 9000–9999 is a safe manual-seed range.
     */
    protected static final AtomicInteger REG_SEQ = new AtomicInteger(9000);

    @ServiceConnection
    protected static final PostgreSQLContainer<?> POSTGRES =
            new PostgreSQLContainer<>("postgres:17-alpine")
                    .withDatabaseName("lims")
                    .withUsername("lims")
                    .withPassword("lims")
                    // PG default max_connections=100 is too low for the IT suite. Each
                    // @SpringBootTest spins up its own HikariPool (default
                    // maximum-pool-size=10) and contexts accumulate across the run; once we
                    // crossed ~160 ITs we started seeing intermittent
                    // "FATAL: sorry, too many clients already" on context load. Bumping the
                    // ceiling buys headroom without changing application behaviour — this is
                    // a test-infra knob only.
                    .withCommand("postgres", "-c", "max_connections=500")
                    .withInitScript("init-schemas.sql");

    static {
        POSTGRES.start();
    }

    /**
     * Belt-and-suspenders: even though {@code @ServiceConnection} on the static field already
     * registers the URL with Spring's {@link DynamicPropertyRegistry}, some IT classes that don't
     * use {@code @ServiceConnection} (e.g. raw {@code @DataJpaTest} slices in the {@code infra}
     * package) still need a hint. This source covers them too without affecting the others.
     */
    @DynamicPropertySource
    static void datasourceProperties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", POSTGRES::getJdbcUrl);
        registry.add("spring.datasource.username", POSTGRES::getUsername);
        registry.add("spring.datasource.password", POSTGRES::getPassword);
    }

    /**
     * Logs in via secured-x's {@code /api/v1/auth/login} endpoint with provider {@code local} and
     * returns the issued JWT access token. The caller is responsible for attaching it as a {@code
     * Authorization: Bearer <jwt>} header on subsequent requests.
     *
     * <p>The seeded test admin (see Chunk 1 Task 1.5) is {@code admin@test.local} / {@code
     * test-password}.
     */
    protected static String loginAs(int port, String email, String password) {
        var http = RestClient.builder().baseUrl("http://localhost:" + port).build();
        var body =
                Map.of(
                        "provider",
                        "local",
                        "payload",
                        Map.of("username", email, "password", password));
        @SuppressWarnings("unchecked")
        Map<String, Object> response =
                http.post()
                        .uri("/api/v1/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .body(body)
                        .retrieve()
                        .body(Map.class);
        return (String) response.get("accessToken");
    }

    /**
     * Convenience factory that composes {@link #loginAs(int, String, String)} for one of the seeded
     * test users (see {@code 202605061002-seed-iam-test-users.yaml}) and returns a {@link
     * RestClient} pre-configured with the issued JWT bearer token. The {@code role} is mapped to
     * the seeded {@code <role>@test.local} email; password is {@code test-password} for every
     * seeded user.
     *
     * <p>Supported role names (case-insensitive): {@code ADMIN}, {@code LAB-MANAGER}, {@code
     * BIOLOGIST}, {@code TECHNICIAN}, {@code RECEPTIONIST}, {@code CASHIER}, {@code ACCOUNTANT}.
     * The acceptance ITs in chunk 6 use {@code RECEPTIONIST} / {@code TECHNICIAN} per spec §9.5
     * permission grid; {@code ADMIN} is used when a single token must satisfy multiple permissions
     * across modules (e.g. seeding catalog data plus opening lab files).
     */
    protected static RestClient restClientFor(int port, String role) {
        var email = role.toLowerCase(Locale.ROOT) + "@test.local";
        var jwt = loginAs(port, email, "test-password");
        return RestClient.builder()
                .baseUrl("http://localhost:" + port)
                .defaultHeader("Authorization", "Bearer " + jwt)
                .build();
    }

    /**
     * A {@link RestClient} bound to the test server's base URL with <em>no</em> {@code
     * Authorization} header. Used by patient-portal ITs to call public paths (e.g. {@code POST
     * /api/v1/portal/login}) and to assert that token-protected portal endpoints reject anonymous
     * callers with 401.
     */
    protected static RestClient restClientAnonymous(int port) {
        return RestClient.builder().baseUrl("http://localhost:" + port).build();
    }

    /**
     * A {@link RestClient} bound to the test server's base URL carrying {@code Authorization:
     * Bearer <token>}. Used by patient-portal ITs to present a portal JWT (minted via {@code POST
     * /api/v1/portal/login}) on the portal's protected endpoints.
     */
    protected static RestClient portalClient(int port, String token) {
        return RestClient.builder()
                .baseUrl("http://localhost:" + port)
                .defaultHeader("Authorization", "Bearer " + token)
                .build();
    }
}
